import { createHash } from 'node:crypto';
import { checkRegister, checkThresholds, type RegisterReport, type ThresholdCheck } from './governance.js';
import type { RegisterItem, SuiteResult, Threshold } from './types.js';

/**
 * UW-13 — the evaluation report. Deterministic suites give byte-identical reports on every run of the same commit (nothing in it
 * depends on the clock or the machine unless the caller stamps it), so a reviewer can re-run it and compare.
 */
export const REPORT_FORMAT = 'xo-evaluation/1';

export interface EvaluationReport {
  readonly format: typeof REPORT_FORMAT;
  readonly run: { readonly commit?: string; readonly node: string; readonly at?: string; readonly suites: readonly string[] };
  readonly suites: readonly SuiteResult[];
  readonly thresholds: readonly ThresholdCheck[];
  readonly register: RegisterReport & { readonly items: readonly RegisterItem[] };
  readonly verdict: {
    /** Ratified thresholds a measure failed: these fail `--check`. */
    readonly failedRatified: readonly string[];
    /** Thresholds still awaiting the owner's ratification. */
    readonly proposals: number;
    /** Whether a first pilot with real data is blocked by the register (UAC-20). */
    readonly pilotGate: 'blocked' | 'clear';
    readonly problems: readonly string[];
  };
}

/** SHA-256 of a value's canonical JSON (object keys sorted), or of bytes and strings as given. */
export function contentHash(value: unknown): string {
  const canonical = (v: unknown): unknown =>
    v instanceof Uint8Array
      ? Buffer.from(v).toString('base64')
      : Array.isArray(v)
        ? v.map(canonical)
        : v !== null && typeof v === 'object'
          ? Object.fromEntries(
              Object.keys(v as object)
                .sort()
                .map((k) => [k, canonical((v as Record<string, unknown>)[k])]),
            )
          : v;
  return createHash('sha256')
    .update(typeof value === 'string' ? value : JSON.stringify(canonical(value)))
    .digest('hex');
}

export function buildEvaluationReport(input: {
  readonly results: readonly SuiteResult[];
  readonly thresholds: readonly Threshold[];
  readonly thresholdProblems?: readonly string[];
  readonly register: readonly RegisterItem[];
  readonly run: { readonly commit?: string; readonly node?: string; readonly at?: string };
}): EvaluationReport {
  const results = [...input.results].sort((a, b) => a.suite.localeCompare(b.suite));
  const measured = new Set(results.map((r) => r.suite));
  // A threshold for a suite that was not run this time is not reported as unmeasured noise.
  const relevant = input.thresholds.filter((t) => measured.has(t.measure.split('/')[0]!));
  const checks = checkThresholds(
    relevant,
    results.flatMap((r) => r.measures),
  );
  const register = checkRegister(input.register);
  return {
    format: REPORT_FORMAT,
    run: {
      ...(input.run.commit !== undefined ? { commit: input.run.commit } : {}),
      node: input.run.node ?? process.versions.node.split('.')[0]!,
      ...(input.run.at !== undefined ? { at: input.run.at } : {}),
      suites: results.map((r) => r.suite),
    },
    suites: results,
    thresholds: checks,
    register: { ...register, items: input.register },
    verdict: {
      failedRatified: checks.filter((c) => c.outcome === 'fail').map((c) => c.measure),
      proposals: checks.filter((c) => c.outcome === 'proposal').length,
      pilotGate: register.pilotBlockers.length === 0 ? 'clear' : 'blocked',
      problems: [
        ...(input.thresholdProblems ?? []),
        ...register.problems,
        ...checks.filter((c) => c.outcome === 'not-measured').map((c) => `${c.measure}: has a threshold but no suite measured it`),
      ],
    },
  };
}

const fmt = (v: number | null, unit: 'ratio' | 'count'): string =>
  v === null ? 'no cases' : unit === 'ratio' ? `${(v * 100).toFixed(1)}%` : String(v);

export function renderReportMarkdown(r: EvaluationReport): string {
  const out: string[] = [
    '# XO evaluation report',
    '',
    '<!-- Generated by `npm run eval -- --write` (packages/evaluation). Do not edit by hand. -->',
    '',
    `Format ${r.format}; Node ${r.run.node}${r.run.commit !== undefined ? `; commit ${r.run.commit}` : ''}${r.run.at !== undefined ? `; run ${r.run.at}` : ''}.`,
    '',
    '## Verdict',
    '',
    `- Ratified thresholds failed: ${r.verdict.failedRatified.length === 0 ? 'none' : r.verdict.failedRatified.join(', ')}.`,
    `- Thresholds awaiting the owner's ratification: ${r.verdict.proposals}. A proposal is shown beside its measure and is never a gate (UAC-19).`,
    `- First pilot with real data: **${r.verdict.pilotGate}**${r.register.pilotBlockers.length > 0 ? ` by ${r.register.pilotBlockers.join(', ')}` : ''} (UAC-20).`,
    ...(r.verdict.problems.length > 0 ? ['', '**Problems:**', ...r.verdict.problems.map((p) => `- ${p}`)] : []),
  ];
  const checkOf = new Map(r.thresholds.map((c) => [c.measure, c]));
  for (const s of r.suites) {
    out.push('', `## ${s.title} (\`${s.suite}\`)`, '', `Evidence for ${s.uac.join(', ')}. Mode: ${s.mode}.`, '');
    for (const set of s.sets)
      out.push(
        `- Labelled set \`${set.id}\` v${set.version}: ${set.cases} cases, ${set.provenance}, sha256 \`${set.contentHash.slice(0, 16)}…\`. ${set.description}`,
      );
    out.push('', '| Measure | Value | Threshold |', '| --- | --- | --- |');
    for (const m of s.measures) {
      const c = checkOf.get(m.id);
      const value = `${fmt(m.value, m.unit)}${m.denominator !== undefined ? ` (${m.numerator}/${m.denominator})` : ''}`;
      const state = {
        proposal: 'proposed',
        pass: 'ratified, met',
        fail: 'ratified, FAILED',
        'no-cases': `${c?.status}, nothing to check`,
        'not-measured': '',
      }[c?.outcome ?? 'not-measured'];
      const threshold = c === undefined ? '' : `${c.bound} (${state})`;
      out.push(`| ${m.title} | ${value} | ${threshold} |`);
    }
    if (s.notes.length > 0) out.push('', '**Notes:**', ...s.notes.map((n) => `- ${n}`));
    out.push('', '**Limits:**', ...s.limits.map((l) => `- ${l}`));
  }
  out.push(
    '',
    '## Commercial readiness register (R1 to R18)',
    '',
    '| Item | Pilot-blocking | Owner | Status | Next |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const i of r.register.items)
    out.push(
      `| ${i.id} ${i.title}${i.titleUnconfirmed === true ? ' (title to confirm)' : ''} | ${i.pilotBlocking ? 'yes' : ''} | ${i.owner} | ${i.status.replace('_', ' ')} | ${(i.next ?? '').replace(/\|/g, '\\|')} |`,
    );
  out.push('');
  return out.join('\n');
}
