import type { Extraction } from './extract.js';
import { addProposal, type ClauseProposal, type ReviewItem } from './model-extract.js';
import { applyReviewDecisions, EMPTY_LEDGER, type ReviewDecision, type ReviewLedger } from './review.js';
import { identifiersIn, type PolicyProgram, type Step } from './program.js';
import { synthesizeTree } from './synthesize.js';

/**
 * The compiler does not guess. When it cannot work something out — a sentence it does not understand, a name the
 * manual never defines, a rule with no outcome, two rules that contradict, an ambiguous unit — it produces a
 * plain-English QUESTION with the evidence quoted, and applies the person's ANSWER through the same deterministic
 * checks as everything else. With or without a model: a model (see `extendWithModel`) may pre-fill proposals, but the
 * questions below are generated by code from the program's structure and are never skipped.
 */
export type QuestionKind =
  | 'reconfirm_ruling'
  | 'map_input'
  | 'resolve_sentence'
  | 'undefined_quantity'
  | 'rename_fact'
  | 'no_outcome'
  | 'conflict'
  | 'missing_target'
  | 'unit_ambiguity';

export interface Question {
  readonly id: string;
  readonly kind: QuestionKind;
  /** plain English, written for a policy owner, not an engineer */
  readonly prompt: string;
  /** exact sentences from the manual the question is about */
  readonly evidence: readonly string[];
  readonly options?: readonly string[];
  readonly suggestion?: string;
  /** a blocking question leaves part of the policy undecided (the tree escalates there) until it is answered */
  readonly blocking: boolean;
  /** what the answer is about: a sentence, a fact name, a step id */
  readonly subject: string;
}

export interface Answer {
  readonly questionId: string;
  /** option chosen, a new name, or free text; see each kind */
  readonly value: string;
  /** for `resolve_sentence`: the rule, written as a checked proposal */
  readonly proposal?: ClauseProposal;
}

const FILLER = new Set([
  'who',
  'which',
  'that',
  'whose',
  'where',
  'has',
  'have',
  'had',
  'made',
  'in',
  'is',
  'was',
  'with',
  'of',
  'the',
  'a',
  'an',
]);

/** Shortens a long extracted name to the noun phrase before the first relative word ("claim_in_which_someone_hurt" → "claim"). */
export function suggestName(name: string): string | undefined {
  const parts = name.split('_').filter(Boolean);
  const cut = parts.findIndex((p, i) => i > 0 && FILLER.has(p));
  const head = (cut === -1 ? parts : parts.slice(0, cut)).slice(0, 3).join('_');
  return head !== '' && head !== name ? head : undefined;
}

const isAwkward = (name: string): boolean =>
  name.split('_').length > 4 ||
  name
    .split('_')
    .slice(1)
    .some((p) => FILLER.has(p));

const IDENT = /^[a-z][a-z0-9_]*$/;

function splitStrings(expr: string): { text: string; isString: boolean }[] {
  const out: { text: string; isString: boolean }[] = [];
  let last = 0;
  for (const m of expr.matchAll(/'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"/g)) {
    out.push({ text: expr.slice(last, m.index), isString: false }, { text: m[0], isString: true });
    last = (m.index ?? 0) + m[0].length;
  }
  out.push({ text: expr.slice(last), isString: false });
  return out;
}
const renameIn = (expr: string, from: string, to: string): string =>
  splitStrings(expr)
    .map((p) => (p.isString ? p.text : p.text.replace(new RegExp(`\\b${from}\\b`, 'g'), to)))
    .join('');

/** Renames a fact everywhere it is used. Returns the program unchanged if the new name is invalid or already taken. */
export function renameFact(program: PolicyProgram, from: string, to: string): PolicyProgram {
  if (!IDENT.test(to) || from === to || program.facts.some((f) => f.name === to) || !program.facts.some((f) => f.name === from))
    return program;
  const re = (e: string): string => renameIn(e, from, to);
  const steps: Step[] = program.steps.map((s) => {
    const scope = s.scope !== undefined && s.scope.var === from ? { ...s.scope, var: to } : s.scope;
    const base = { ...s, ...(scope !== undefined ? { scope } : {}) };
    if (s.kind === 'gate') return { ...base, kind: 'gate', when: re(s.when) } as Step;
    if (s.kind === 'assign')
      return {
        ...base,
        kind: 'assign',
        set: Object.fromEntries(Object.entries(s.set).map(([k, v]) => [k === from ? to : k, re(v)])),
      } as Step;
    return {
      ...base,
      kind: 'finish',
      ...(s.when !== undefined ? { when: re(s.when) } : {}),
      ...(s.amount !== undefined ? { amount: re(s.amount) } : {}),
    } as Step;
  });
  return {
    ...program,
    facts: program.facts.map((f) => (f.name === from ? { ...f, name: to } : f)),
    steps,
    ...(program.kindVar === from ? { kindVar: to } : {}),
    ...(program.amountField === from ? { amountField: to } : {}),
  };
}

const readsOf = (s: Step): string[] =>
  s.kind === 'gate'
    ? identifiersIn(s.when)
    : s.kind === 'assign'
      ? Object.values(s.set).flatMap(identifiersIn)
      : [...identifiersIn(s.when ?? ''), ...identifiersIn((s.amount ?? '').replace(/^=/, ''))];

/** Every question the compiler has about this extraction. Deterministic; the same input always yields the same questions. */
export function clarify(extraction: Extraction): Question[] {
  const p = extraction.program;
  const qs: Question[] = [];
  let n = 0;
  const id = (k: string): string => `${k}-${++n}`;

  for (const u of extraction.unrecognized)
    qs.push({
      id: id('sentence'),
      kind: 'resolve_sentence',
      prompt: `The manual says: “${u.sentence}” I could not turn this into a rule. Does it change how a case is decided? If yes, state the condition and the outcome; if it is only background, say so.`,
      evidence: [u.sentence],
      options: ['rule', 'background'],
      blocking: true,
      subject: u.sentence,
    });

  const defined = new Set(p.steps.flatMap((s) => (s.kind === 'assign' ? Object.keys(s.set) : [])));
  const known = new Set(p.facts.map((f) => f.name));
  const seen = new Set<string>();
  for (const s of p.steps)
    for (const r of readsOf(s))
      if (!known.has(r) && !defined.has(r) && !seen.has(r) && !(s.kind === 'assign' && r in s.set)) {
        seen.add(r);
        qs.push({
          id: id('undefined'),
          kind: 'undefined_quantity',
          prompt: `A rule uses “${r.replace(/_/g, ' ')}” but the manual never says what it is. Is it something known about each case (an input), or is it calculated — and if so, how?`,
          evidence: [s.source.sentence],
          options: ['input', 'calculated'],
          blocking: true,
          subject: r,
        });
      }

  for (const f of p.facts)
    if (isAwkward(f.name)) {
      const sug = suggestName(f.name);
      qs.push({
        id: id('rename'),
        kind: 'rename_fact',
        prompt: `I named this input “${f.name}” (${f.description}). Is there a shorter name your systems use for it?`,
        evidence: [],
        ...(sug !== undefined ? { suggestion: sug } : {}),
        blocking: false,
        subject: f.name,
      });
    }

  for (const s of p.steps)
    if (s.kind === 'gate' && s.outcome.decision === 'escalate' && (s.outcome.target === undefined || s.outcome.target.trim() === ''))
      qs.push({
        id: id('target'),
        kind: 'missing_target',
        prompt: `This rule sends a case to a person, but the manual does not say to whom: “${s.source.sentence}” Who receives it?`,
        evidence: [s.source.sentence],
        blocking: true,
        subject: s.id,
      });

  const byWhen = new Map<string, Step[]>();
  for (const s of p.steps)
    if (s.kind === 'gate')
      byWhen.set(`${s.scope?.var ?? ''}|${(s.scope?.values ?? []).join(',')}|${s.when}`, [
        ...(byWhen.get(`${s.scope?.var ?? ''}|${(s.scope?.values ?? []).join(',')}|${s.when}`) ?? []),
        s,
      ]);
  for (const group of byWhen.values()) {
    const outcomes = new Set(group.map((g) => (g.kind === 'gate' ? `${g.outcome.decision}:${g.outcome.target ?? ''}` : '')));
    if (group.length > 1 && outcomes.size > 1)
      qs.push({
        id: id('conflict'),
        kind: 'conflict',
        prompt: 'Two rules apply to exactly the same situation but give different outcomes. Which one wins?',
        evidence: group.map((g) => g.source.sentence),
        options: group.map((g) => g.id),
        blocking: true,
        subject: group.map((g) => g.id).join(','),
      });
  }

  const synth = synthesizeTree(p);
  if (synth.failClosedPaths.length > 0)
    qs.push({
      id: id('outcome'),
      kind: 'no_outcome',
      prompt: `The manual never says what happens to a case when none of the rules above applies${synth.failClosedPaths.every((x) => x === 'decision') ? '' : ` (for: ${synth.failClosedPaths.join(', ')})`}. Should it be approved, or sent to a person?`,
      evidence: [],
      options: ['escalate', 'approve'],
      suggestion: 'escalate',
      blocking: true,
      subject: synth.failClosedPaths.join(','),
    });

  for (const f of p.facts)
    if (f.derivable === true && /calendar (?:days?|hours?)/i.test(f.description))
      qs.push({
        id: id('unit'),
        kind: 'unit_ambiguity',
        prompt: `“${f.name}” is counted in calendar days. Does the manual mean calendar days or business days?`,
        evidence: p.steps
          .filter((s) => readsOf(s).includes(f.name))
          .map((s) => s.source.sentence)
          .slice(0, 2),
        options: ['calendar', 'business'],
        suggestion: 'calendar',
        blocking: false,
        subject: f.name,
      });
  return qs;
}

export interface AnswerOutcome {
  readonly extraction: Extraction;
  readonly ledger: ReviewLedger;
  /** questions still open (unanswered, or whose answer was refused) */
  readonly open: readonly Question[];
  readonly refused: readonly { readonly questionId: string; readonly reasons: readonly string[] }[];
}

/** Applies answers. Nothing is applied unless it passes the deterministic checks; refusals carry their reasons. */
export function applyAnswers(
  extraction: Extraction,
  questions: readonly Question[],
  answers: readonly Answer[],
  ledger: ReviewLedger = EMPTY_LEDGER,
): AnswerOutcome {
  let program = extraction.program;
  const refused: { questionId: string; reasons: string[] }[] = [];
  const answered = new Set<string>();
  const qOf = (a: Answer): Question | undefined => questions.find((q) => q.id === a.questionId);

  // 1. sentences go through the review loop (checked proposals, fixpoint ordering)
  const decisions: ReviewDecision[] = [];
  const items: ReviewItem[] = extraction.unrecognized.map((u) => ({ ...u, reasons: ['not recognised'] }));
  for (const a of answers) {
    const q = qOf(a);
    if (q?.kind !== 'resolve_sentence') continue;
    if (a.value === 'background') decisions.push({ sentence: q.subject, action: 'reject', note: 'answered: background' });
    else if (a.proposal !== undefined) decisions.push({ sentence: q.subject, action: 'edit', proposal: a.proposal });
    else refused.push({ questionId: q.id, reasons: ['a rule needs a proposal (condition and outcome)'] });
    answered.add(q.id);
  }
  const reviewed = applyReviewDecisions({ ...extraction, program }, items, decisions, ledger);
  program = reviewed.extraction.program;
  for (const r of reviewed.refused) {
    const q = questions.find((x) => x.subject === r.sentence);
    if (q) {
      refused.push({ questionId: q.id, reasons: [...r.reasons] });
      answered.delete(q.id);
    }
  }

  // 2. the other kinds
  for (const a of answers) {
    const q = qOf(a);
    if (q === undefined || q.kind === 'resolve_sentence') continue;
    if (q.kind === 'rename_fact') {
      const next = renameFact(program, q.subject, a.value.trim());
      if (next === program) refused.push({ questionId: q.id, reasons: [`“${a.value}” is not a valid, unused lower_snake name`] });
      else {
        program = next;
        answered.add(q.id);
      }
    } else if (q.kind === 'undefined_quantity') {
      if (a.value === 'input') {
        program = {
          ...program,
          facts: [
            ...program.facts,
            { name: q.subject, type: 'number', description: `${q.subject.replace(/_/g, ' ')} (supplied with each case)` },
          ],
        };
        answered.add(q.id);
      } else if (a.proposal !== undefined && a.proposal.step.kind === 'assign') {
        const clause = { rule: '', section: 'answer', sentence: q.evidence[0] ?? q.subject };
        const res = addProposal(program, { ...a.proposal, quote: a.proposal.quote }, clause, 'operator', 900 + answered.size);
        if ('program' in res) {
          program = res.program;
          answered.add(q.id);
        } else refused.push({ questionId: q.id, reasons: res.reasons });
      } else refused.push({ questionId: q.id, reasons: ['say “input”, or give the calculation as a proposal'] });
    } else if (q.kind === 'no_outcome') {
      // "escalate" is what the tree already does; recording the answer is what makes it a decision of the owner
      if (a.value === 'escalate') answered.add(q.id);
      else refused.push({ questionId: q.id, reasons: ['approving by default needs an explicit finish rule written as a proposal'] });
    } else if (q.kind === 'unit_ambiguity') {
      if (a.value === 'business')
        program = {
          ...program,
          facts: program.facts.map((f) =>
            f.name === q.subject ? { ...f, description: f.description.replace(/calendar/gi, 'business') } : f,
          ),
        };
      answered.add(q.id);
    } else if (q.kind === 'missing_target') {
      program = {
        ...program,
        steps: program.steps.map((s) =>
          s.id === q.subject && s.kind === 'gate' ? { ...s, outcome: { ...s.outcome, target: a.value.trim() } } : s,
        ),
      };
      answered.add(q.id);
    } else if (q.kind === 'conflict') {
      const loser = (q.options ?? []).filter((o) => o !== a.value);
      if (!(q.options ?? []).includes(a.value)) refused.push({ questionId: q.id, reasons: ['choose one of the listed rules'] });
      else {
        program = { ...program, steps: program.steps.filter((s) => !loser.includes(s.id)) };
        answered.add(q.id);
      }
    }
  }
  const next: Extraction = { ...reviewed.extraction, program };
  return { extraction: next, ledger: reviewed.ledger, open: questions.filter((q) => !answered.has(q.id)), refused };
}
