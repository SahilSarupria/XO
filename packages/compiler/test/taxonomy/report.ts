import type { CaseResult } from './harness.js';
import type { Target } from './targets.js';

/** Markdown table of one run. Everything here is SYNTHETIC data: a regression guard, not accuracy evidence. */
export function renderReport(results: readonly CaseResult[], targets: Readonly<Record<string, Target>>): string {
  const f = (n: number | undefined): string => (n === undefined ? '-' : n.toFixed(2));
  const rows = results.map((r) => {
    const gap = targets[r.id]?.knownGap;
    const outcome = r.opened ? `${r.pagesWithText}/${r.pages} pages` : `refused ${r.errorCode ?? ''}`;
    return `| ${r.id} | ${r.category} | ${r.tier} | ${outcome} | ${r.pagesFlaggedForRecovery} | ${r.unaccountedPages} | ${r.qualityState ?? '-'} | ${f(r.wordF1)} | ${f(r.sequenceScore)} | ${Math.round(r.ms)} | ${r.tokens} | ${r.usd} | ${gap === undefined ? '' : `KNOWN GAP: ${gap}`} |`;
  });
  return [
    '# Extraction failure-taxonomy report',
    '',
    'SYNTHETIC documents generated by `packages/compiler/test/taxonomy`. These are regression guards for known failure classes.',
    'They are NOT evidence of accuracy on real insurance documents.',
    '',
    '| case | category | tier | outcome | flagged for recovery | unaccounted | quality | word F1 | order | ms | tokens | USD | note |',
    '|---|---|---|---|---|---|---|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}
