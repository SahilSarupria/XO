import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { approvalIdentity, canonicalJson, evaluateDecide, externalIdempotencyKey, type DecideStep } from '../src/index.js';

const out = (n: string): string => fileURLToPath(new URL(`../conformance/${n}`, import.meta.url));
const d = (id: string, outputs: DecideStep['outputs'], method: DecideStep['method']): DecideStep => ({
  id,
  type: 'decide',
  determinism: 'deterministic',
  timeoutMs: 1,
  outputs,
  method,
});

const tier = d(
  'tier',
  { tier: { type: 'enum', enum: ['high', 'low'] } },
  {
    kind: 'rules',
    rules: [{ id: 'big', when: "amount >= 100 && region != 'x'", set: { tier: 'high' } }],
    onNoMatch: 'default',
    default: { tier: 'low' },
  },
);
const fee = d(
  'fee',
  { fee: { type: 'number' }, capped: { type: 'boolean' } },
  { kind: 'formula', set: { fee: 'min(round(amount * 0.0725, 2), 50)', capped: 'fee >= 50' } },
);
const rate = d(
  'rate',
  { rate: { type: 'number' } },
  {
    kind: 'lookup',
    keys: ['cls'],
    rows: [
      { cls: 'a', rate: 2.5 },
      { cls: 'b', rate: 4 },
    ],
    onMiss: 'escalate',
  },
);
const strict = d(
  'strict',
  { tier: { type: 'enum', enum: ['high'] } },
  { kind: 'rules', rules: [{ id: 'r', when: 'amount > 0', set: { tier: 'high' } }], onNoMatch: 'escalate' },
);

const cases = [
  [tier, { amount: 100, region: 'y' }],
  [tier, { amount: 99.99, region: 'y' }],
  [tier, { amount: 500, region: 'x' }],
  [tier, { region: 'y' }],
  [fee, { amount: 100 }],
  [fee, { amount: 10000 }],
  [fee, { amount: 0.1 }],
  [rate, { cls: 'b' }],
  [rate, { cls: 'c' }],
  [rate, { cls: 1 }],
  [strict, { amount: -1 }],
] as const;

const doc = {
  note: 'Generated by scripts/emit-vectors.ts from the reference evaluator. A conforming runtime must reproduce every `expected` exactly (numbers are IEEE-754 binary64).',
  semantics: '1.0',
  decide: cases.map(([step, inputs]) => ({ step, inputs, expected: evaluateDecide(step, inputs) })),
  identities: [
    {
      workflow: { id: 'w', version: '1.0.0' },
      step: 'approve_refund',
      instance: { runId: 'run_1', index: 0 },
      approvalIdentity: approvalIdentity({ id: 'w', version: '1.0.0' }, 'approve_refund', { runId: 'run_1', index: 0 }),
    },
    {
      workflow: { id: 'w', version: '1.0.0' },
      step: 'approve_refund',
      instance: { runId: 'run_1', index: 3 },
      approvalIdentity: approvalIdentity({ id: 'w', version: '1.0.0' }, 'approve_refund', { runId: 'run_1', index: 3 }),
    },
  ],
  externalKeys: [
    {
      workflow: { id: 'w', version: '1.0.0' },
      step: 'pay',
      rendered: 'claim:42',
      key: externalIdempotencyKey({ id: 'w', version: '1.0.0' }, 'pay', 'claim:42'),
    },
  ],
  canonicalJson: [{ value: { b: 1, a: [2, { d: 1, c: 2 }] }, canonical: canonicalJson({ b: 1, a: [2, { d: 1, c: 2 }] }) }],
};
writeFileSync(out('semantics-vectors-1.0.json'), `${JSON.stringify(doc, null, 2)}\n`);
console.log('wrote vectors');
